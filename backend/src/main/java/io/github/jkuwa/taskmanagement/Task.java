package io.github.jkuwa.taskmanagement;

import java.time.LocalDate;
import java.time.LocalDateTime;

import org.hibernate.annotations.ColumnDefault;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * カード（タスク）を表すクラス。DB の tasks テーブルの1行に対応する。
 *
 * <p>@Entity を付けると、JPA（Hibernate）がこのクラスを「DB のテーブルに対応するクラス」として扱う。
 * application.properties の spring.jpa.hibernate.ddl-auto=update により、
 * 起動時にこのクラスの内容をもとに tasks テーブルが自動で作られる。
 *
 * <p>フィールド名は自動で「小文字＋アンダースコア」の列名に変換される（例：dueDate → due_date）。
 * 列の定義は docs/database.md の tasks テーブルに合わせている。
 */
@Entity
@Table(name = "tasks") // テーブル名を指定する（指定しないとクラス名の task になる）
public class Task {
	// ---- フィールド（テーブルの列）の定義 ----
	/**
	 * 主キー。保存するときに DB が自動で番号を振る（IDENTITY）。
	 *
	 * <p>docs/database.md では GENERATED ALWAYS AS IDENTITY だが、Hibernate が作るのは
	 * GENERATED BY DEFAULT AS IDENTITY になる（ALWAYS は id を手で指定できない、BY DEFAULT は指定もできる）。
	 * アプリからは id を指定しないので、動きは同じ。
	 * 
	 * {@code @Id}：主キーであることを示す
	 * {@code @GeneratedValue}：主キーの値を自動で生成することを示す
	 * {@code strategy}：誰がどうやって番号を決めるかを指定する
	 * {@code GenerationType.IDENTITY}：DB が自動で番号を振る
	 * {@code private Integer id;}：主キーの値
	 */
	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Integer id;  // private：外からの書き換えなどを防ぐ

	/** タイトル（必須） */
	@Column(nullable = false, length = 255)
	private String title;

	/** 説明文。長い文章も入るように TEXT 型にする */
	@Column(columnDefinition = "text")
	private String description;

	/** 優先度（high / medium / low）。未設定なら null */
	@Column(length = 10)
	private String priority;

	/** 期限。未設定なら null */
	private LocalDate dueDate;

	/**
	 * 状態（todo / in_progress / done）。どの列に入っているかを表す。
	 *
	 * <p>@ColumnDefault はテーブルを作るときの DEFAULT 値。
	 * ただし Hibernate は保存時に null も含めて全部の列の値を送るので、Java 側でも初期値 "todo" を入れておく。
	 */
	@Column(nullable = false, length = 20)
	@ColumnDefault("'todo'")
	private String status = "todo";  // Java側の初期値

	/** 列の中での並び順 */
	@Column(nullable = false)
	@ColumnDefault("0")
	private Integer position = 0;

	/**
	 * 作成日時。あとから変更しない。
	 * （@CreationTimestampだけだと、アプリから保存したときしか現在時刻が入らないので、psql などで直接 INSERT したときのために、DB 側にも DEFAULT CURRENT_TIMESTAMP を付けている）
	 * 
	 * {@code @ColumnDefault}：テーブルを作るときの DEFAULT 値。DB側の初期値。
	 */
	@CreationTimestamp // データを最初に保存するときに、Hibernateが現在時刻を入れるためのアノテーション（Localの時刻）
	@Column(nullable = false, updatable = false)
	@ColumnDefault("CURRENT_TIMESTAMP") // 空の時はDB側で現在時刻を入れる（DBの時刻（UTC））
	private LocalDateTime createdAt;

	/** 更新日時。保存・更新するたびに Hibernate が現在時刻を入れる */
	@UpdateTimestamp
	@Column(nullable = false)
	@ColumnDefault("CURRENT_TIMESTAMP")
	private LocalDateTime updatedAt;

	// ---- コンストラクタ ----
	/**
	 * 引数なしのコンストラクタ。JPA が DB から読み込んだデータでオブジェクトを作るときに使う。（JPAの仕様で必要）
	 * アプリのコードからは使わないので protected にしている。
	 * protected：同じパッケージのクラス、もしくはこのクラスを継承したクラスであれば、アクセスできる。
	 */
	// 空のタスクを作る。
	protected Task() {
	}

	/**
	 * タイトル・状態（列）・並び順を指定してカードを作る。カードを追加する API で使う。
	 * Javaのコンストラクタはクラス名と同じ名前にする決まり。
	 * 同じ名前のコンストラクタでも、引数の数や型が違えば複数作れる（オーバーロード）。
	 * ここでは引数なしのもの（JPA 用）と、この3つの引数を取るものの2つがある。
	 *
	 * <p>説明文・期限・優先度は未設定（null）で作る。あとから詳細画面で設定する。
	 *
	 * @param title    タイトル
	 * @param status   状態（todo / in_progress / done）
	 * @param position 列の中での並び順
	 */
	public Task(String title, String status, Integer position) {
		this.title = title;
		this.status = status;
		this.position = position;
	}

	// ---- 更新 ----
	/**
	 * 詳細画面で編集できる項目（タイトル・説明文・期限・優先度）をまとめて書き換える。
	 * カードを更新する API で使う。
	 *
	 * <p>項目ごとに setter を作ると、どこからでも1項目ずつ書き換えられてしまうので、
	 * 「詳細画面の内容で更新する」という1つのメソッドにまとめている。
	 * 入力のチェックは TaskService で済ませてから呼ぶ。
	 *
	 * <p>JPA は、トランザクションの中で読み込んだエンティティの値が変わると、
	 * トランザクションの終わりに自動で UPDATE 文を実行する（変更の検知）。
	 * 更新日時（updatedAt）も @UpdateTimestamp で自動で入る。
	 *
	 * @param title       タイトル
	 * @param description 説明文（未設定なら null）
	 * @param dueDate     期限（未設定なら null）
	 * @param priority    優先度（未設定なら null）
	 */
	public void update(String title, String description, LocalDate dueDate, String priority) {
		this.title = title;
		this.description = description;
		this.dueDate = dueDate;
		this.priority = priority;
	}

	// ---- getter（値を取り出すメソッド）----
	// フィールドの値を取得するためのメソッド。フィールドがprivateなので、メソッドを通さないと外部からアクセスできない。
	public Integer getId() {
		return id;
	}

	public String getTitle() {
		return title;
	}

	public String getDescription() {
		return description;
	}

	public String getPriority() {
		return priority;
	}

	public LocalDate getDueDate() {
		return dueDate;
	}

	public String getStatus() {
		return status;
	}

	public Integer getPosition() {
		return position;
	}

	public LocalDateTime getCreatedAt() {
		return createdAt;
	}

	public LocalDateTime getUpdatedAt() {
		return updatedAt;
	}
}
