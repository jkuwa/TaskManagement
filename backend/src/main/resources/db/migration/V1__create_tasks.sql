-- tasks（カード）テーブルを作る。列の意味は docs/database.md を参照。
--
-- Flyway は起動時に db/migration のファイルを V1, V2… の順に1回ずつ実行し、
-- 実行したものを flyway_schema_history テーブルに記録する。一度実行したファイルは書き換えない
-- （テーブルを変えたいときは、V2__… のように新しいファイルを足す）。
--
-- 作成日時・更新日時は、タイムゾーン付きの日時（TIMESTAMPTZ）にする。
-- タイムゾーンなしの TIMESTAMP だと、アプリ（日本時間）が入れた値と DB の DEFAULT（UTC）が入れた値が
-- 区別できずに混ざってしまう。TIMESTAMPTZ は「世界共通のどの時点か」で保存するので、どちらから入れてもずれない。

CREATE TABLE tasks (
	id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title       VARCHAR(255)   NOT NULL,
	description TEXT,
	priority    VARCHAR(10),
	due_date    DATE,
	status      VARCHAR(20)    NOT NULL DEFAULT 'todo',
	position    INTEGER        NOT NULL DEFAULT 0,
	created_at  TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at  TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
