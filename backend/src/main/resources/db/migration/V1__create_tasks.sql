-- tasks（カード）テーブルを作る。列の意味は docs/database.md を参照。
--
-- Flyway は起動時に db/migration のファイルを V1, V2… の順に1回ずつ実行し、
-- 実行したものを flyway_schema_history テーブルに記録する。一度実行したファイルは書き換えない
-- （テーブルを変えたいときは、V3__… のように新しいファイルを足す）。
--
-- この V1 は、Flyway を入れる前に Hibernate（ddl-auto=update）が作っていたテーブルと同じ定義にしている。

CREATE TABLE tasks (
	id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	title       VARCHAR(255) NOT NULL,
	description TEXT,
	priority    VARCHAR(10),
	due_date    DATE,
	status      VARCHAR(20)  NOT NULL DEFAULT 'todo',
	position    INTEGER      NOT NULL DEFAULT 0,
	created_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
