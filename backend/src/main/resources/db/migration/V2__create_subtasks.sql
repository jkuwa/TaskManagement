-- subtasks（サブタスク）テーブルを作る。列の意味は docs/database.md を参照。
--
-- task_id は親のカード（tasks.id）を指す外部キー。
-- ON DELETE CASCADE を付けているので、カードを削除するとそのカードのサブタスクも DB が自動で削除する。
--
-- サブタスクはカードごとに取り出すので、task_id に索引（インデックス）を付けて速く探せるようにする。
-- （PostgreSQL は主キーには自動で索引を作るが、外部キーには作らない）

CREATE TABLE subtasks (
	id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	task_id    INTEGER        NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
	title      VARCHAR(255)   NOT NULL,
	done       BOOLEAN        NOT NULL DEFAULT FALSE,
	created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX subtasks_task_id_idx ON subtasks (task_id);
